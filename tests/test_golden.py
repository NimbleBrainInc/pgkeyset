"""The cursors this library issues and the SQL that resumes them, pinned byte for byte.

Agents and UIs hold cursors issued by running servers, and pass them back after a deploy. A
cursor issued today must decode to the same key, and resume at the same position, under any
later version of this code. So both halves are frozen here, for each value kind a key can
hold and each predicate shape:

  * ``golden/cursors.txt``: the cursor each case's key encodes to. The test encodes the key
    and compares, then decodes the frozen cursor and compares it with the key.
  * ``golden/sql.txt``: the statement ``apply`` builds from the frozen cursor (ORDER BY and
    the strictly-after predicate, with the casts the typed binds add) and its bound values.

The golden files are frozen output, not generated by the test. A failure here means a cursor
in flight would decode differently or resume somewhere else: a breaking change, which needs
the maintainers' explicit sign-off before a golden file is edited.
"""

from __future__ import annotations

import uuid
from datetime import UTC, datetime, timedelta, timezone
from decimal import Decimal
from pathlib import Path
from typing import Any

import pytest
import sqlalchemy as sa
from sqlalchemy.dialects.postgresql.asyncpg import PGDialect_asyncpg

from conftest import ITEM
from pgkeyset import Listing, Sort

GOLDEN = Path(__file__).parent / "golden"
# asyncpg, so the SQL is what Postgres receives whatever SQLAlchemy's default driver is.
_ASYNCPG = PGDialect_asyncpg()

_BAND = sa.case((ITEM.c.status == "draft", 0), else_=1)

NEWEST = Listing("items", Sort.desc(ITEM.c.created_at), Sort.desc(ITEM.c.id))
OLDEST = Listing("items:asc", Sort.asc(ITEM.c.created_at), Sort.asc(ITEM.c.id))
SEEN_FIRST = Listing("items:seen", Sort.asc(ITEM.c.seen_at, nulls="first"), Sort.asc(ITEM.c.id))
SEEN_LAST = Listing("items:-seen", Sort.desc(ITEM.c.seen_at, nulls="last"), Sort.desc(ITEM.c.id))
MIXED = Listing("items:status", Sort.asc(ITEM.c.status), Sort.desc(ITEM.c.id))
BAND = Listing(
    "review",
    Sort.asc(_BAND, value=lambda r: 0),
    Sort.desc(ITEM.c.created_at),
    Sort.desc(ITEM.c.id),
)
AMOUNT = Listing(
    "amount", Sort.asc(sa.cast(ITEM.c.status, sa.Numeric), value=lambda r: 0), Sort.asc(ITEM.c.id)
)
SMALL = Listing(
    "small",
    Sort.asc(sa.cast(ITEM.c.status, sa.SmallInteger), value=lambda r: 0),
    Sort.asc(ITEM.c.id),
)
BIG = Listing(
    "big", Sort.desc(sa.cast(ITEM.c.status, sa.BigInteger), value=lambda r: 0), Sort.desc(ITEM.c.id)
)

PRICE = Listing(
    "price",
    Sort.desc(sa.cast(ITEM.c.status, sa.Numeric(10, 2)), value=lambda r: 0),
    Sort.desc(ITEM.c.id),
)
BY_STATUS = Listing(
    "by_status",
    Sort.asc(
        sa.cast(ITEM.c.status, sa.Enum("draft", "sent", name="item_status")), value=lambda r: 0
    ),
    Sort.asc(ITEM.c.id),
)
BY_UUID = Listing(
    "by_uuid",
    Sort.desc(ITEM.c.created_at),
    Sort.desc(sa.cast(ITEM.c.id, sa.Uuid), value=lambda r: 0),
)
BY_UUID_TEXT = Listing(
    "by_uuid_text",
    Sort.asc(sa.cast(ITEM.c.id, sa.Uuid(as_uuid=False)), value=lambda r: 0),
)
UID = uuid.UUID("abcdef01-2345-6789-abcd-ef0123456789")

WHEN = datetime(2026, 3, 4, 5, 6, 7, 891011, tzinfo=UTC)
HST = timezone(timedelta(hours=-10))

#: name -> (listing, key encoded, key the frozen cursor decodes to).
CASES: dict[str, tuple[Listing, tuple[Any, ...], tuple[Any, ...]]] = {
    # Timestamps: microseconds kept, whole seconds (isoformat drops the fraction), another zone.
    "ts_desc": (NEWEST, (WHEN, "it_1"), (WHEN, "it_1")),
    "ts_whole_second": (
        NEWEST,
        (WHEN.replace(microsecond=0), "it_1"),
        (WHEN.replace(microsecond=0), "it_1"),
    ),
    "ts_other_zone": (
        NEWEST,
        (datetime(2026, 3, 3, 19, 6, 7, 891011, tzinfo=HST), "it_2"),
        (WHEN, "it_2"),
    ),
    "ts_asc": (OLDEST, (WHEN, "it_1"), (WHEN, "it_1")),
    # NULL bands at both ends, from inside the band and from a value.
    "nulls_first_in_band": (SEEN_FIRST, (None, "it_3"), (None, "it_3")),
    "nulls_first_value": (SEEN_FIRST, (WHEN, "it_3"), (WHEN, "it_3")),
    "nulls_last_in_band": (SEEN_LAST, (None, "it_4"), (None, "it_4")),
    "nulls_last_value": (SEEN_LAST, (WHEN, "it_4"), (WHEN, "it_4")),
    # Strings, mixed directions, and text JSON escapes.
    "str_mixed": (MIXED, ("draft", "it_5"), ("draft", "it_5")),
    "str_escaped": (
        MIXED,
        ('Zoë "q" \\ 🚀', "it_6"),
        ('Zoë "q" \\ 🚀', "it_6"),
    ),
    # A computed int band ahead of a timestamp.
    "int_band": (BAND, (1, WHEN, "it_7"), (1, WHEN, "it_7")),
    # Numerics travel as their decimal strings, trailing zeros and all.
    "num": (AMOUNT, (Decimal("27.10"), "it_8"), (Decimal("27.10"), "it_8")),
    "num_negative_small": (
        AMOUNT,
        (Decimal("-0.000001"), "it_8"),
        (Decimal("-0.000001"), "it_8"),
    ),
    "num_long": (
        AMOUNT,
        (Decimal("12345678901234567890.123456789"), "it_8"),
        (Decimal("12345678901234567890.123456789"), "it_8"),
    ),
    # Ints at their column widths; a bigint past a float's 53 bits stays exact.
    "smallint": (SMALL, (-32768, "it_9"), (-32768, "it_9")),
    "bigint": (BIG, (2**53 + 1, "it_9"), (2**53 + 1, "it_9")),
    # A declared numeric(10, 2): its scale stays in the cursor and the bind's cast.
    "num_scaled": (PRICE, (Decimal("12345678.90"), "it_8"), (Decimal("12345678.90"), "it_8")),
    # A string enum's label, bound as the enum type.
    "enum": (BY_STATUS, ("sent", "it_5"), ("sent", "it_5")),
    # A uuid travels in its canonical lowercase form, and decodes to a UUID or to text.
    "uuid": (BY_UUID, (WHEN, UID), (WHEN, UID)),
    "uuid_as_text": (BY_UUID_TEXT, (str(UID),), (str(UID),)),
}


def _golden_cursors() -> dict[str, str]:
    lines = (GOLDEN / "cursors.txt").read_text().splitlines()
    return dict(line.split("\t") for line in lines if line and not line.startswith("#"))


def _golden_sql() -> dict[str, str]:
    sections: dict[str, str] = {}
    for block in (GOLDEN / "sql.txt").read_text().split("== ")[1:]:
        name, _, body = block.partition(" ==\n")
        sections[name] = body.rstrip("\n")
    return sections


def render(listing: Listing, cursor: str) -> str:
    """The statement ``apply`` builds for ``cursor``, and its bound values."""
    compiled = listing.apply(sa.select(ITEM.c.id), cursor).compile(dialect=_ASYNCPG)
    sql = "\n".join(line.rstrip() for line in str(compiled).splitlines())
    params = "\n".join(f"{k} = {v!r}" for k, v in sorted(compiled.params.items()))
    return f"{sql}\n{params}"


def test_every_case_is_frozen() -> None:
    assert set(_golden_cursors()) == set(CASES)
    assert set(_golden_sql()) == set(CASES)


@pytest.mark.parametrize("case", sorted(CASES))
def test_a_key_encodes_to_its_frozen_cursor(case: str) -> None:
    listing, key, _ = CASES[case]
    assert listing.encode(key) == _golden_cursors()[case]


@pytest.mark.parametrize("case", sorted(CASES))
def test_a_frozen_cursor_decodes_to_its_key(case: str) -> None:
    listing, _, decoded = CASES[case]
    key = listing.decode(_golden_cursors()[case])
    assert key == decoded
    # Equal instants are not enough: the zone a timestamp binds in is part of the position.
    assert [type(v) for v in key] == [type(v) for v in decoded]
    for value in key:
        if isinstance(value, datetime):
            assert value.tzinfo is UTC


@pytest.mark.parametrize("case", sorted(CASES))
def test_a_frozen_cursor_resumes_with_its_frozen_sql(case: str) -> None:
    listing, _, _ = CASES[case]
    assert render(listing, _golden_cursors()[case]) == _golden_sql()[case]
